class SlurmArrayRunner:
    """Generate SLURM sbatch scripts for distributed rfm-pipeline execution.

    Parameters
    ----------
    config
        Distributed execution configuration.
    manifest_path
        Path to the shard manifest JSONL file.
    output_root
        Root directory for shard outputs (must be on shared filesystem).
    repo_root
        Absolute path to the BSM repository root (where pixi.toml lives).
        Defaults to current working directory.
    """

    def __init__(
        self,
        config: DistributedConfig,
        manifest_path: str | Path,
        output_root: str | Path,
        repo_root: str | Path | None = None,
    ):
        self.config = config
        self.manifest_path = Path(manifest_path)
        self.output_root = Path(output_root)
        self.repo_root = Path(repo_root) if repo_root else Path.cwd()

        # Validate config before generating scripts
        errors = config.validate()
        if errors:
            raise ValueError(f"Invalid DistributedConfig: {errors}")

        self._shards: list[ShardManifest] = []
        if self.manifest_path.exists():
            self._shards = load_manifest(self.manifest_path)

    @property
    def n_shards(self) -> int:
        """Number of shards in the manifest."""
        return len(self._shards)

    def _common_vars(self, stage: str) -> dict:
        cfg = self.config
        slurm = cfg.slurm
        kestrel = cfg.kestrel
        spill = cfg.spill
        gpu = cfg.gpu

        log_dir = slurm.resolve_log_dir(cfg.run_id)
        scratch_root = os.path.expandvars(spill.scratch_root)

        return {
            "stage": stage,
            "run_id": cfg.run_id,
            "account": slurm.account,
            "partition": slurm.partition,
            "walltime": slurm.walltime,
            "memory_mb": slurm.memory_gb * 1024,
            "cpus_per_task": slurm.cpus_per_task,
            "max_task_idx": max(0, self.n_shards - 1),
            "max_concurrent": slurm.max_concurrent_array_tasks,
            "array_spec": (
                _task_ids_to_array_spec(
                    list(range(self.n_shards)), slurm.max_concurrent_array_tasks
                )
                if self.n_shards > 0
                else f"0%{slurm.max_concurrent_array_tasks}"
            ),
            "log_dir": log_dir,
            "requeue_line": (
                "#SBATCH --requeue"
                if slurm.requeue
                else "# --requeue disabled (Kestrel PreemptMode=OFF)"
            ),
            "pixi_env_path": cfg.pixi_env_path,
            "pixi_cache_dir": kestrel.pixi_cache_dir,
            "manifest_path": str(self.manifest_path.resolve()),
            "output_root": str(self.output_root.resolve()),
            "scratch_root": scratch_root,
            "repo_root": str(self.repo_root.resolve()),
            "n_shards": self.n_shards,
            "debug_partition": kestrel.debug_partition,
            # GPU vars
            "gpu_partition": gpu.gpu_partition,
            "gpu_walltime": gpu.gpu_walltime,
            "n_gpus": gpu.n_gpus,
            "gpu_host_memory_mb": slurm.memory_gb * 1024,
            "xgboost_tree_method": gpu.xgboost_tree_method,
        }

    def generate_stage_script(self, stage: str, task_ids: list[int] | None = None) -> str:
        """Generate a SLURM array sbatch script for a pipeline stage.

        Parameters
        ----------
        stage
            Pipeline stage name (e.g. 'interaction_discovery').
        task_ids
            Optional explicit list of task IDs to include in the array spec.
            If provided, only those IDs are submitted (sparse restart spec).
            If None, all shards (0 … n_shards-1) are included.

        Returns
        -------
        str
            Complete sbatch script content.
        """
        if self.n_shards == 0:
            raise ValueError("No shards in manifest — run build_manifest() first")
        vars_ = self._common_vars(stage)
        if task_ids is not None:
            vars_["array_spec"] = _task_ids_to_array_spec(
                task_ids, self.config.slurm.max_concurrent_array_tasks
            )
        return _STAGE_SBATCH_TEMPLATE.format(**vars_)

    def generate_reduce_script(
        self,
        stage: str,
        after_job_id: int | None = None,
        reduce_walltime: str = "02:00:00",
        reduce_memory_gb: int = 32,
    ) -> str:
        """Generate a SLURM reduce job sbatch script.

        The reduce job aggregates shard outputs into a single stage artifact.
        When *after_job_id* is given, the job depends on ``afterany:<job_id>``
        so it runs after all array tasks finish regardless of their exit codes.
        The script itself checks that all ``_SUCCESS.json`` markers exist before
        proceeding, so partial failures cause it to self-abort with a clear
        message rather than silently aggregating incomplete data.

        Parameters
        ----------
        stage
            Pipeline stage name.
        after_job_id
            SLURM job ID of the array job to depend on. If provided, adds
            ``#SBATCH --dependency=afterany:<job_id>``.
        reduce_walltime
            Walltime for the reduce job.
        reduce_memory_gb
            Memory (GB) for the reduce job.

        Returns
        -------
        str
            Complete sbatch script content.
        """
        vars_ = self._common_vars(stage)
        vars_["reduce_walltime"] = reduce_walltime
        vars_["reduce_memory_mb"] = reduce_memory_gb * 1024
        if after_job_id:
            vars_["dependency_line"] = f"#SBATCH --dependency=afterany:{after_job_id}"
        else:
            vars_["dependency_line"] = "# No dependency (submit after array job completes)"
        return _REDUCE_SBATCH_TEMPLATE.format(**vars_)

    def generate_diagnostic_script(self) -> str:
        """Generate a smoke-test diagnostic sbatch script."""
        return _DIAGNOSTIC_SBATCH_TEMPLATE.format(**self._common_vars("diagnostic"))

    def generate_gpu_stage_script(self, stage: str, task_ids: list[int] | None = None) -> str:
        """Generate a GPU-accelerated SLURM array sbatch script.

        Targets the GPU partition (gpu-h100s on Kestrel) and sets
        BSM_INTERACTION_DEVICE=cuda so the shard worker uses the
        XGBoost + SHAP GPU backend for interaction discovery.

        Parameters
        ----------
        stage
            Pipeline stage name. GPU acceleration is most effective for
            interaction_discovery.
        task_ids
            Optional explicit list of task IDs (sparse restart). If None,
            all shards are included.

        Returns
        -------
        str
            Complete sbatch script content.
        """
        if self.n_shards == 0:
            raise ValueError("No shards in manifest — run build_manifest() first")
        if not self.config.gpu.enabled:
            raise ValueError(
                "GPU script requested but config.gpu.enabled is False. "
                "Set distributed.gpu.enabled: true in your config."
            )
        vars_ = self._common_vars(stage)
        if task_ids is not None:
            vars_["array_spec"] = _task_ids_to_array_spec(
                task_ids, self.config.slurm.max_concurrent_array_tasks
            )
        return _GPU_STAGE_SBATCH_TEMPLATE.format(**vars_)

    def generate_gpu_diagnostic_script(self) -> str:
        """Generate a GPU environment smoke-test sbatch script."""
        return _GPU_DIAGNOSTIC_SBATCH_TEMPLATE.format(**self._common_vars("gpu_diagnostic"))

    def write_scripts(
        self,
        output_dir: str | Path,
        stage: str = "interaction_discovery",
        reduce_walltime: str = "02:00:00",
        reduce_memory_gb: int = 32,
        task_ids: list[int] | None = None,
    ) -> dict[str, Path]:
        """Write all sbatch scripts to output_dir and make them executable.

        Parameters
        ----------
        output_dir
            Directory to write scripts into (created if needed).
        stage
            Pipeline stage to target.
        reduce_walltime
            Walltime for the reduce job.
        reduce_memory_gb
            Memory (GB) for the reduce job.
        task_ids
            Optional explicit list of incomplete task IDs. When provided and
            non-empty, the stage array script uses a sparse ``--array`` spec
            covering only those IDs (idempotent restart).  When provided as
            an empty list, the stage script is omitted entirely (all shards
            already complete — only the reduce script is written).

        Returns
        -------
        dict[str, Path]
            Mapping of script name → absolute path.
        """
        out = Path(output_dir)
        out.mkdir(parents=True, exist_ok=True)

        # task_ids=None → full range; task_ids=[] → skip array, reduce only;
        # task_ids=[...] → sparse spec for those IDs
        write_array = (task_ids is None) or (len(task_ids) > 0)

        scripts = {}
        if self.n_shards > 0:
            if write_array:
                stage_script = out / f"submit_{stage}_array.sh"
                stage_script.write_text(self.generate_stage_script(stage, task_ids=task_ids))
                _make_executable(stage_script)
                scripts["stage"] = stage_script

            reduce_script = out / f"submit_{stage}_reduce.sh"
            reduce_script.write_text(
                self.generate_reduce_script(
                    stage,
                    reduce_walltime=reduce_walltime,
                    reduce_memory_gb=reduce_memory_gb,
                )
            )
            _make_executable(reduce_script)
            scripts["reduce"] = reduce_script

            # GPU scripts (when GPU is enabled in config)
            if self.config.gpu.enabled and write_array:
                gpu_script = out / f"submit_{stage}_gpu_array.sh"
                gpu_script.write_text(self.generate_gpu_stage_script(stage, task_ids=task_ids))
                _make_executable(gpu_script)
                scripts["gpu_stage"] = gpu_script

        diag_script = out / "submit_diagnostic.sh"
        diag_script.write_text(self.generate_diagnostic_script())
        _make_executable(diag_script)
        scripts["diagnostic"] = diag_script

        if self.config.gpu.enabled:
            gpu_diag_script = out / "submit_gpu_diagnostic.sh"
            gpu_diag_script.write_text(self.generate_gpu_diagnostic_script())
            _make_executable(gpu_diag_script)
            scripts["gpu_diagnostic"] = gpu_diag_script

        submit_all = out / "submit_all.sh"
        submit_all.write_text(_make_submit_all_script(scripts, stage))
        _make_executable(submit_all)
        scripts["submit_all"] = submit_all

        logger.info("[slurm] wrote %d scripts to %s", len(scripts), out)
        return scripts

    def status(self) -> dict[str, int]:
        """Return a summary of shard statuses from the manifest."""
        if not self._shards:
            return {}
        return manifest_summary(self._shards)

    def submit(
        self,
        script_path: str | Path,
        dry_run: bool = False,
    ) -> int | None:
        """Submit an sbatch script and return the job ID.

        Parameters
        ----------
        script_path
            Path to the sbatch script.
        dry_run
            If True, print the sbatch command but do not execute it.

        Returns
        -------
        int or None
            SLURM job ID, or None if dry_run=True or submission fails.
        """
        cmd = ["sbatch", str(script_path)]
        if dry_run:
            print(f"[dry-run] Would submit: {' '.join(cmd)}")
            return None
        try:
            result = subprocess.run(cmd, capture_output=True, text=True, check=True)
            # sbatch output: "Submitted batch job 12345"
            job_id = int(result.stdout.strip().split()[-1])
            logger.info("[slurm] submitted job %d from %s", job_id, script_path)
            return job_id
        except subprocess.CalledProcessError as e:
            logger.error("[slurm] sbatch failed: %s\n%s", e, e.stderr)
            raise


def _make_executable(path: Path) -> None:
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def _make_submit_all_script(scripts: dict[str, Path], stage: str) -> str:
    stage_path = scripts.get("stage")
    gpu_stage_path = scripts.get("gpu_stage")
    reduce_path = scripts.get("reduce")
    diag_path = scripts.get("diagnostic")
    primary_stage_path = gpu_stage_path or stage_path

    lines = [
        "#!/bin/bash",
        "# Submit all BSM HPC jobs for stage: " + stage,
        "# Run this from the repo root after pixi install --locked",
        "set -euo pipefail",
        "",
    ]
    if diag_path:
        lines += [
            "# Step 0: Smoke test (optional — run first on a new cluster)",
            f"# sbatch {diag_path.name}",
            "",
        ]
    if primary_stage_path:
        lines += [
            f"ARRAY_JOB_ID=$(sbatch --parsable {primary_stage_path.name})",
            'echo "Submitted array job: $ARRAY_JOB_ID"',
            "",
        ]
    if reduce_path:
        lines += [
            f"REDUCE_JOB_ID=$(sbatch --parsable --dependency=afterany:$ARRAY_JOB_ID {reduce_path.name})",  # noqa: E501
            'echo "Submitted reduce job: $REDUCE_JOB_ID (depends on $ARRAY_JOB_ID)"',
            "",
            "echo 'Monitor progress:'",
            "echo '  squeue -u $USER'",
            "echo '  tail -f logs/bsm_" + stage + "_*.out'",
        ]
    return "\n".join(lines) + "\n"
